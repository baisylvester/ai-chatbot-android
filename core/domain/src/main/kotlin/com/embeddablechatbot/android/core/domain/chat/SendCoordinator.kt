/** Process-wide scope for work that must outlive a screen (cancelled explicitly on account change). */
@Qualifier
@Retention(AnnotationRetention.BINARY)
annotation class ApplicationScope

object MessageRules {
    const val MAX_CHARS = 4000

    sealed interface Check {
        data class Valid(val text: String) : Check
        data object Empty : Check
        data class TooLong(val length: Int) : Check
    }

    /** The server trims and accepts 1–4,000 characters; the trimmed text is what the request ID is bound to. */
    fun check(raw: String): Check {
        val text = raw.trim()
        return when {
            text.isEmpty() -> Check.Empty
            text.length > MAX_CHARS -> Check.TooLong(text.length)
            else -> Check.Valid(text)
        }
    }
}

data class ToolActivity(val name: String, val running: Boolean, val steps: List<String>, val waiting: Int?, val failed: Boolean)

/** Provisional, in-memory view of a reply being generated by this device. Never persisted. */
data class LiveReply(
    val requestId: String,
    val conversationId: String,
    val accepted: Boolean = false,
    val provisionalText: String = "",
    val citations: List<Citation> = emptyList(),
    val tools: List<ToolActivity> = emptyList(),
)

sealed interface SendStart {
    data class Started(val requestId: String) : SendStart
    data object Empty : SendStart
    data class TooLong(val length: Int) : SendStart

    /** An earlier send in this conversation is unresolved; resolve it before sending another. */
    data class Blocked(val pending: PendingSend) : SendStart
}

/**
 * Owns the lifecycle of user sends. Rules:
 * - one stable request ID per user send, persisted with the exact normalized text before submission;
 * - a definite refusal keeps the same ID for a safe retry; an uncertain result is reconciled from
 *   server state first, and a new request ID is never generated silently;
 * - work runs in an application scope so leaving a screen does not cancel an in-flight send.
 */
@Singleton
class SendCoordinator @Inject constructor(
    private val repository: ConversationRepository,
    private val ids: IdGenerator,
    private val clock: Clock,
    @param:ApplicationScope private val scope: CoroutineScope,
) {
    private val _live = MutableStateFlow<Map<String, LiveReply>>(emptyMap())
    val liveReplies: StateFlow<Map<String, LiveReply>> = _live.asStateFlow()

    private val jobs = mutableMapOf<String, Job>()
    private val lock = Mutex()

    suspend fun send(conversationId: String, raw: String, emailManager: Boolean, stream: Boolean): SendStart {
        val text = when (val check = MessageRules.check(raw)) {
            MessageRules.Check.Empty -> return SendStart.Empty
            is MessageRules.Check.TooLong -> return SendStart.TooLong(check.length)
            is MessageRules.Check.Valid -> check.text
        }
        val pending = lock.withLock {
            repository.pendingSends(conversationId).firstOrNull()?.let { return SendStart.Blocked(it) }
            PendingSend(ids.newId(), conversationId, text, emailManager, clock.now(), PendingState.Submitting)
                .also { repository.savePendingSend(it) }
        }
        launchSubmit(pending, stream)
        return SendStart.Started(pending.requestId)
    }

    /** Resubmits a definitely-refused or no-trace send with the SAME request ID and text. */
    suspend fun retry(requestId: String, stream: Boolean): Boolean {
        val pending = lock.withLock {
            val found = repository.allPendingSends().firstOrNull { it.requestId == requestId } ?: return false
            if (found.state != PendingState.NotAccepted || jobs[requestId]?.isActive == true) return false
            found.copy(state = PendingState.Submitting, errorMessage = null).also { repository.savePendingSend(it) }
        }
        launchSubmit(pending, stream)
        return true
    }

    /** Drops a send the server definitely did not accept; returns its text for the composer. */
    suspend fun discard(requestId: String): String? = lock.withLock {
        val found = repository.allPendingSends().firstOrNull { it.requestId == requestId } ?: return null
        if (found.state != PendingState.NotAccepted) return null
        repository.deletePendingSend(requestId)
        found.text
    }

    /**
     * Resolves unresolved sends of [conversationId] from server state: after process death, a lost
     * connection, or while another device's reply is running.
     */
    suspend fun reconcile(conversationId: String) {
        val candidates = lock.withLock {
            repository.pendingSends(conversationId).filter { it.state != PendingState.NotAccepted && jobs[it.requestId]?.isActive != true }
        }
        if (candidates.isEmpty()) return
        val sync = repository.syncMessages(conversationId)
        if (sync is Outcome.Err) {
            if (sync.error is AppError.NotFound) candidates.forEach { repository.deletePendingSend(it.requestId) }
            else candidates.filter { it.state == PendingState.Submitting }
                .forEach { repository.savePendingSend(it.copy(state = PendingState.Uncertain)) }
            return
        }
        val conversation = (sync as Outcome.Ok).value
        val committedRequestIds = repository.committedRequestIds(conversationId)
        lock.withLock {
            for (pending in candidates) {
                if (jobs[pending.requestId]?.isActive == true) continue
                val turn = conversation.lastTurn
                when {
                    turn?.requestId == pending.requestId && turn.status.isTerminal -> repository.deletePendingSend(pending.requestId)
                    turn?.requestId == pending.requestId -> repository.savePendingSend(pending.copy(state = PendingState.Running, errorMessage = null))
                    pending.requestId in committedRequestIds -> repository.deletePendingSend(pending.requestId)
                    else -> repository.savePendingSend(
                        pending.copy(state = PendingState.NotAccepted, errorMessage = NOT_DELIVERED),
                    )
                }
            }
        }
    }

    /** Cancels local work for the previous account. Server-side work is not reversed by this. */
    suspend fun cancelAll() {
        lock.withLock {
            jobs.values.forEach { it.cancel() }
            jobs.clear()
        }
        _live.value = emptyMap()
    }

    private suspend fun launchSubmit(pending: PendingSend, stream: Boolean) {
        lock.withLock {
            _live.update { it + (pending.requestId to LiveReply(pending.requestId, pending.conversationId)) }
            jobs[pending.requestId] = scope.launch {
                try {
                    submit(pending, stream)
                } finally {
                    _live.update { it - pending.requestId }
                }
            }
        }
    }

    private suspend fun submit(pending: PendingSend, stream: Boolean) {
        val result = repository.submitMessage(
            pending.conversationId, pending.requestId, pending.text, pending.emailManager, stream,
        ) { event -> onEvent(pending.requestId, event) }
        lock.withLock { jobs.remove(pending.requestId) }
        when (result) {
            is Outcome.Ok -> {
                repository.deletePendingSend(pending.requestId)
                repository.syncMessages(pending.conversationId)
            }
            is Outcome.Err -> handleFailure(pending, result.error)
        }
    }

    private suspend fun handleFailure(pending: PendingSend, error: AppError) {
        fun refused(message: String) = pending.copy(state = PendingState.NotAccepted, errorMessage = message)
        when (error) {
            is AppError.Conflict -> when (error.reason) {
                ErrorReason.RequestRunning -> repository.savePendingSend(pending.copy(state = PendingState.Running, errorMessage = null))
                ErrorReason.LeaseLost -> markUncertainAndReconcile(pending)
                else -> repository.savePendingSend(refused(error.message))
            }
            is AppError.NotFound -> repository.deletePendingSend(pending.requestId)
            is AppError.Forbidden -> repository.savePendingSend(refused(error.message))
            is AppError.RateLimited -> repository.savePendingSend(
                refused(error.retryAfterSeconds?.let { "Too many requests. Try again in $it seconds." } ?: "Too many requests. Wait a moment."),
            )
            is AppError.Invalid -> repository.savePendingSend(refused(error.message))
            AppError.Unauthorized -> repository.savePendingSend(refused("Sign in again to send this message."))
            is AppError.Unavailable -> repository.savePendingSend(refused(error.message))
            is AppError.NotConfigured -> repository.savePendingSend(refused(error.message))
            is AppError.Gone -> repository.savePendingSend(refused(error.message))
            is AppError.Network -> if (error.uncertain) markUncertainAndReconcile(pending)
            else repository.savePendingSend(refused("Couldn't reach the server. Nothing was sent."))
            is AppError.Server, is AppError.Protocol -> markUncertainAndReconcile(pending)
        }
    }

    private suspend fun markUncertainAndReconcile(pending: PendingSend) {
        repository.savePendingSend(pending.copy(state = PendingState.Uncertain, errorMessage = UNCERTAIN))
        reconcile(pending.conversationId)
    }

    private fun onEvent(requestId: String, event: SendEvent) {
        _live.update { all ->
            val current = all[requestId] ?: return@update all
            val next = when (event) {
                is SendEvent.Accepted -> current.copy(accepted = true)
                is SendEvent.Token -> current.copy(accepted = true, provisionalText = current.provisionalText + event.text)
                is SendEvent.Sources -> current.copy(citations = event.citations)
                is SendEvent.Tool -> current.copy(tools = mergeTool(current.tools, event))
                is SendEvent.Done -> current
            }
            all + (requestId to next)
        }
    }

    private fun mergeTool(tools: List<ToolActivity>, event: SendEvent.Tool): List<ToolActivity> {
        val running = event.phase == "start"
        val updated = ToolActivity(event.name, running, event.steps, event.waiting, event.failed)
        val index = tools.indexOfLast { it.name == event.name && it.running }
        return if (!running && index >= 0) tools.toMutableList().also { it[index] = updated } else tools + updated
    }

    companion object {
        const val UNCERTAIN = "The connection dropped. Checking whether the server received this message…"
        const val NOT_DELIVERED = "The server has no record of this message. Retry sends the same request, so it can't run twice."
    }
}
